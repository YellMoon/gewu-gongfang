'use strict';
// UTF-8: original course confirmation and actual retained timetable; no mocked cloud writes.
const assert=require('node:assert/strict'),path=require('node:path');
module.exports=async({page,out,save,fixture,releaseNavigation})=>{
  const id=fixture.studentId;
  const projection=()=>page.evaluate(()=>window.desktopIdentitySessionProvider.listCloudBusinessProjection());
  const baseline=await projection(),course=baseline.courses.find(c=>c.id===id),lesson=baseline.schedules.find(s=>s.id===id);
  assert(course&&lesson);assert.equal(lesson.course_name,course.display_name);
  const navigate=async(name)=>{
    await page.locator('.app-shell__collapse-button').click();
    if(!await page.getByRole('menuitem',{name,exact:true}).isVisible())await page.getByRole('menuitem',{name:'calendar 教务',exact:true}).click();
    await page.getByRole('menuitem',{name,exact:true}).click();await releaseNavigation();
  };
  const card=page.locator('[data-schedule-id="'+id+'"]');
  await navigate('calendar 课程表');await card.waitFor();await card.scrollIntoViewIfNeeded();
  const originalText=await card.innerText();assert(originalText.includes(course.display_name));assert.match(originalText,/原上课地址\s+09:00-10:30/);
  await page.screenshot({path:path.join(out,'course-history-01-before.png'),scale:'css'});
  await navigate('book 课程信息');
  const row=page.locator('[data-row-key="'+id+'"]');await row.waitFor();
  const initialDrafts=await page.evaluate(()=>window.desktopAuthority.list());
  await row.getByRole('button',{name:'delete 删除',exact:true}).click();
  await page.locator('.ant-popconfirm:visible').getByRole('button',{name:/^取\s*消$/}).click();
  assert.deepEqual(await page.evaluate(()=>window.desktopAuthority.list()),initialDrafts);
  await row.getByRole('button',{name:'delete 删除',exact:true}).click();await page.context().setOffline(true);
  await page.locator('.ant-popconfirm:visible').getByRole('button',{name:/^确\s*定$/}).click();
  await page.waitForFunction(async id=>(await window.desktopAuthority.list()).some(d=>d.type==='course.delete.v1'&&d.payload.id===id&&d.status==='awaiting_confirmation'),id);
  const draft=await page.evaluate(async id=>(await window.desktopAuthority.list()).find(d=>d.type==='course.delete.v1'&&d.payload.id===id&&d.status==='awaiting_confirmation'),id);
  await page.context().setOffline(false);assert.deepEqual(await projection(),baseline,'reconnection must not submit deletion');
  await page.locator('.sync-status-trigger').click();
  await page.locator('[data-row-key="'+draft.id+'"]').getByRole('button',{name:'查看并确认',exact:true}).click();
  const dialog=page.getByRole('dialog');await dialog.waitFor();await dialog.getByText(course.display_name,{exact:true}).waitFor();
  await dialog.getByRole('button',{name:'确认并发送',exact:true}).hover();
  await page.screenshot({path:path.join(out,'course-history-02-confirm.png'),scale:'css',animations:'disabled'});
  assert.deepEqual(await projection(),baseline,'opening confirmation must not submit deletion');
  await dialog.getByRole('button',{name:'确认并发送',exact:true}).click();await dialog.waitFor({state:'hidden',timeout:45000});
  await page.waitForFunction(async id=>['completed','conflict'].includes((await window.desktopAuthority.list()).find(d=>d.id===id)?.status),draft.id,{timeout:45000});
  const stored=await page.evaluate(async id=>(await window.desktopAuthority.list()).find(d=>d.id===id),draft.id);
  save('course-history-submission',{id:stored.id,status:stored.status,receipt:stored.receipt,lastError:stored.lastError});assert.equal(stored.status,'completed');
  const after=await projection();assert(!after.courses.some(c=>c.id===id));
  for(const key of ['schedules','students','student_contacts','payments','consumptions'])assert.deepEqual(after[key],baseline[key],key+' must remain intact after course deletion');
  await page.reload();await page.locator('.app-shell').waitFor({timeout:45000});
  await page.getByText('系统加载中...',{exact:true}).waitFor({state:'hidden',timeout:45000});
  await navigate('book 课程信息');assert.equal(await page.locator('[data-row-key="'+id+'"]').count(),0);
  await navigate('calendar 课程表');await card.waitFor();await card.scrollIntoViewIfNeeded();
  assert.equal(await card.innerText(),originalText,'original course name, address and time survive reload');
  const reloaded=await projection();assert.deepEqual(reloaded.schedules,baseline.schedules);assert(!reloaded.courses.some(c=>c.id===id));
  await page.screenshot({path:path.join(out,'course-history-03-reloaded.png'),scale:'css'});
  save('course-history-ui-readback',{before:baseline,after,reloaded,originalCardText:originalText,reloadedCardText:await card.innerText()});
  return {originalCancelUnchanged:true,offlineDraft:true,reconnectDidNotSubmit:true,reviewDidNotSubmit:true,confirmedDeletion:true,courseAbsentAfterReload:true,originalLessonCardRetained:true,ledgerProjectionUnchanged:true};
};
