'use strict';
// UTF-8: original deletion controls, offline confirmation and cloud disappearance; DB history is verified by the runner.
const assert=require('node:assert/strict');
const path=require('node:path');
module.exports=async({page,out,save,fixture,releaseNavigation})=>{
  const projection=()=>page.evaluate(()=>window.desktopIdentitySessionProvider.listCloudBusinessProjection());
  const baseline=(await projection()).students.find(s=>s.id===fixture.studentId);
  assert(baseline); assert.equal(baseline.name,fixture.name);
  const initialDrafts=await page.evaluate(()=>window.desktopAuthority.list());
  const row=page.locator('[data-row-key="'+fixture.studentId+'"]');
  await row.getByRole('cell',{name:fixture.name,exact:true}).waitFor();
  await row.getByRole('button',{name:'delete 删除',exact:true}).click();
  await page.locator('.ant-popconfirm:visible').getByRole('button',{name:/^取\s*消$/}).click();
  assert.deepEqual(await page.evaluate(()=>window.desktopAuthority.list()),initialDrafts);
  await row.getByRole('button',{name:'delete 删除',exact:true}).click();
  await page.context().setOffline(true);
  await page.locator('.ant-popconfirm:visible').getByRole('button',{name:/^确\s*定$/}).click();
  await page.waitForFunction(async id=>(await window.desktopAuthority.list()).some(d=>d.type==='student.delete.v1'&&d.payload.id===id&&d.status==='awaiting_confirmation'),fixture.studentId);
  const draft=await page.evaluate(async id=>(await window.desktopAuthority.list()).find(d=>d.type==='student.delete.v1'&&d.payload.id===id&&d.status==='awaiting_confirmation'),fixture.studentId);
  await page.context().setOffline(false);
  assert.deepEqual((await projection()).students.find(s=>s.id===fixture.studentId),baseline,'reconnection must not submit deletion');
  await page.locator('.sync-status-trigger').click();
  await page.locator('[data-row-key="'+draft.id+'"]').getByRole('button',{name:'查看并确认',exact:true}).click();
  const dialog=page.getByRole('dialog'); await dialog.waitFor();
  await dialog.getByText(fixture.name,{exact:true}).waitFor();
  await dialog.getByRole('button',{name:'确认并发送',exact:true}).hover();
  await page.screenshot({path:path.join(out,'student-history-01-confirm.png'),scale:'css',animations:'disabled'});
  assert.deepEqual((await projection()).students.find(s=>s.id===fixture.studentId),baseline,'review alone must not submit deletion');
  await dialog.getByRole('button',{name:'确认并发送',exact:true}).click();
  await dialog.waitFor({state:'hidden',timeout:45000});
  await page.waitForFunction(async id=>['completed','conflict'].includes((await window.desktopAuthority.list()).find(d=>d.id===id)?.status),draft.id,{timeout:45000});
  const stored=await page.evaluate(async id=>(await window.desktopAuthority.list()).find(d=>d.id===id),draft.id);
  save('student-history-submission',{id:stored.id,status:stored.status,receipt:stored.receipt,lastError:stored.lastError});
  assert.equal(stored.status,'completed');
  assert(!(await projection()).students.some(s=>s.id===fixture.studentId));
  await page.reload();
  await page.locator('.app-shell').waitFor({timeout:45000});
  await page.getByText('系统加载中...',{exact:true}).waitFor({state:'hidden',timeout:45000});
  await page.locator('.app-shell__collapse-button').click();
  await page.getByRole('menuitem',{name:'team 资源',exact:true}).click();
  await page.getByRole('menuitem',{name:'user 学生',exact:true}).click();
  await releaseNavigation();
  await page.getByRole('button',{name:'plus 添加学生',exact:true}).waitFor();
  assert.equal(await page.getByRole('cell',{name:fixture.name,exact:true}).count(),0);
  assert(!(await projection()).students.some(s=>s.id===fixture.studentId));
  await page.screenshot({path:path.join(out,'student-history-02-reloaded.png'),scale:'css'});
  return {originalCancelUnchanged:true,offlineDraft:true,reconnectDidNotSubmit:true,reviewDidNotSubmit:true,
    confirmedDeletion:true,reloadAbsent:true};
};
